"""Seeded, parameterised level and game generators for the h25 synthetic suite.

Five families, each a multi-level game whose mechanic persists across levels
while the board, the piece count and the optimal solution length grow:

  push     push-box-to-target (Sokoban), 1-3 boxes; generated by random PULLS
           from the solved state, so every level is solvable by construction
  lights   lights-out: a click toggles a cell and its 4 neighbours; clear the board
  keydoor  maze with coloured keys and matching doors (1-2), lava = GAME_OVER
  recolor  click a canvas cell to cycle its colour; match the pattern on the right
  tilt     gravity / sliding tiles: every tile slides until blocked; rest the
           player tile on the goal (1-3 tiles)

Every level's optimal length is computed by ``solve.bfs`` over the same rules
the game file embeds. ``baseline_actions`` (the RHAE human baseline) is
``ceil(HUMAN_FACTOR * optimal)`` with ``HUMAN_FACTOR = 1.5``: the measured
public games put humans well above optimal, and 1.5x keeps a level beaten at the
optimum capped (1.5^2 = 2.25 > 1.15) while a 2x-optimal agent still scores
(0.75^2 = 0.56). ``optimal_actions`` is written next to it in metadata.json.

Half the games (seeded) carry a HUD move meter: two extra rows on top, a bar
that shrinks one step per counted action; running out is GAME_OVER. Its budget
is ``2 * optimal + 10`` per level, so it never binds an optimal solver.
"""
from __future__ import annotations

import math
import random
from collections import deque
from typing import Any, Dict, List, Optional, Tuple

from . import rules
from .solve import SearchLimit, optimal_length

FAMILIES = ("push", "lights", "keydoor", "recolor", "tilt")
LETTER = {"push": "p", "lights": "l", "keydoor": "k", "recolor": "c", "tilt": "t"}
HUMAN_FACTOR = 1.5
MAX_TRIES = 400

Cell = Tuple[int, int]


class GenerationFailed(RuntimeError):
    pass


def human_baseline(opt: int) -> int:
    return max(1, int(math.ceil(HUMAN_FACTOR * opt)))


def _border(w: int, h: int) -> List[Cell]:
    return [(x, y) for y in range(h) for x in range(w) if x in (0, w - 1) or y in (0, h - 1)]


def _solve(lv: Dict[str, Any], max_states: int = 300_000) -> Optional[int]:
    try:
        return optimal_length(lv, max_states)
    except SearchLimit:
        return None


