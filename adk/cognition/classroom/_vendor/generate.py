def game_spec(index: int, suite_seed: Any = 0, family: Optional[str] = None) -> Dict[str, Any]:
    """The full, JSON-serialisable description of synthetic game ``index``.

    Depends only on ``(suite_seed, index, family)``: ``random.Random`` seeded
    with a str is stable across processes and PYTHONHASHSEED."""
    fam = family or FAMILIES[index % len(FAMILIES)]
    rng = random.Random("h25:%s:%d:%s" % (suite_seed, index, fam))
    n_levels = rng.choice((3, 4, 5))
    levels: List[Dict[str, Any]] = []
    opts: List[int] = []
    for i in range(n_levels):
        lv, opt = GENERATORS[fam](rng, i)
        # JSON-normalise (tuples -> lists) so the spec round-trips unchanged
        lv = {k: ([list(c) for c in v] if k in ("walls", "lava", "targets", "boxes", "tiles") else v)
              for k, v in lv.items()}
        levels.append(lv)
        opts.append(opt)
    colours = list(range(16))
    rng.shuffle(colours)
    roles = rules.SY_FAMILY_ROLES[fam]
    palette = [-1] * rules.N_ROLES
    for r, c in zip(roles, colours):
        palette[r] = c
    spare = colours[len(roles):]
    meter = [2 * o + 10 for o in opts] if rng.random() < 0.5 else None
    short = "%s%03d" % (LETTER[fam], index)
    return {
        "short_id": short,
        "family": fam,
        "suite_seed": suite_seed,
        "index": index,
        "levels": levels,
        "optimal_actions": opts,
        "baseline_actions": [human_baseline(o) for o in opts],
        "human_factor": HUMAN_FACTOR,
        "actions": [1, 2, 3, 4] if fam in rules.SY_MOVE_FAMILIES else [6],
        "colors": palette,
        "background": palette[rules.R_FLOOR],
        "letterbox": spare[0],
        "meter": meter,
        "meter_color": spare[1],
        "meter_empty": spare[2],
    }
