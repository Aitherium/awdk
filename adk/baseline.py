"""``adk baseline`` -- the ready-to-code component baseline for an AitherOS box.

ONE table, one collector, one verdict. ``install.ps1`` / ``install.sh`` cannot
import Python, so they carry their own literal ids; an installer test asserts the
two lists agree. This module is the machine-readable half.

Why a NEW verb and not ``adk doctor``: ``doctor`` is generated by ``gen_aw_doctor.py``
and is rewritten on every regeneration, so a hand-edit there is reverted and fails
the parity gate. Also ``doctor`` reports the whole stack (which brick pairs with
which); this reports whether the developer baseline is present, current, and still
the configuration that was validated.

Exit codes (never 0 on silence):

* ``adk baseline``        0 every required component is present, 1 something is
                          missing or below its floor.
* ``adk baseline --sync`` 0 the box matches ``~/.aither/baseline.json``, 1 it has
                          drifted, 2 there is no record to compare against.

stdlib only: a diagnostic that cannot run because a dependency is missing is
worthless precisely when you need it.
"""

