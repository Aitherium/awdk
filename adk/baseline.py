_VERSION_RE = re.compile(r"(\d+)\.(\d+)(?:\.(\d+))?")
_FLOOR_RE = re.compile(r">=\s*(\d+\.\d+(?:\.\d+)?)")


def record_path() -> str:
    """``~/.aither/baseline.json`` -- the validated configuration."""
    home = os.environ.get("AITHER_HOME") or os.path.join(os.path.expanduser("~"), ".aither")
    return os.path.join(home, "baseline.json")


def _parse_version(text: str | None) -> tuple[int, ...] | None:
    if not text:
        return None
    m = _VERSION_RE.search(text)
    if not m:
        return None
    return tuple(int(g) for g in m.groups() if g is not None)


def _pad(value: tuple[int, ...], size: int) -> tuple[int, ...]:
    return value + (0,) * (size - len(value))


def meets(version: str | None, expected: str) -> bool:
    """True when *version* satisfies the ``>=x.y`` floor in *expected*."""
    have = _parse_version(version)
    floor = _FLOOR_RE.search(expected or "")
    if have is None or floor is None:
        return False
    need = _parse_version(floor.group(1))
    if need is None:
        return False
    size = max(len(have), len(need))
    return _pad(have, size) >= _pad(need, size)


def probe(command: str, args: list[str]) -> str | None:
    """Return the version string a command reports, or None when it is absent."""
    exe = shutil.which(command)
    if not exe:
        return None
    try:
        proc = subprocess.run(
            [exe, *args],
            capture_output=True,
            encoding="utf-8",
            errors="replace",
            timeout=15,
        )
    except (OSError, subprocess.SubprocessError):
        return None
    text = "%s\n%s" % (proc.stdout or "", proc.stderr or "")
    found = _VERSION_RE.search(text)
    return found.group(0) if found else None


def state_of(version: str | None, expected: str) -> str:
    if version is None:
        return "missing"
    if not meets(version, expected):
        return "outdated"
    return "present"


def _default_command(command: str) -> str:
    """The name the component is actually installed under on this box.

    Debian-family distributions ship ``python3`` and no bare ``python``. The
    installer records the name it probed, but the no-record path (``adk
    baseline``) must resolve the same one, or a box the installer just
    configured reports python missing.
    """
    if command == "python" and shutil.which("python") is None and shutil.which("python3"):
        return "python3"
    return command


def collect(entry: dict) -> dict:
    """One report row: component, version, expected, state, fix."""
    version = probe(_default_command(entry["command"]), entry.get("args") or ["--version"])
    return {
        "component": entry["component"],
        "version": version,
        "expected": entry["expected"],
        "state": state_of(version, entry["expected"]),
        "fix": entry.get("fix", ""),
    }


def rows() -> list[dict]:
    return [collect(entry) for entry in BASELINE]


def format_rows(items: list[dict]) -> list[str]:
    """Human report. Never prints a fix line for a component that is present."""
    lines = ["  %-14s %-16s %-10s %s" % ("COMPONENT", "VERSION", "EXPECTED", "STATE")]
    for row in items:
        lines.append(
            "  %-14s %-16s %-10s %s"
            % (
                row["component"],
                row["version"] or "-",
                row["expected"],
                row["state"],
            )
        )
        if row["state"] != "present" and row["fix"]:
            lines.append("  %-14s -> %s" % ("", row["fix"]))
    return lines


def _entry_for(name: str, record: dict) -> dict:
    for entry in BASELINE:
        if entry["component"] == name:
            # The record was written by the installer on the box being synced
            # and carries the command that actually exists there (Linux records
            # ``python3``). Judging it by the canonical ``python`` would report
            # the component the installer just verified as missing.
            command = record.get("command") or entry["command"]
            if command != entry["command"]:
                entry = dict(entry, command=command)
            return entry
    # A record from a newer installer: judge it by its own fields.
    return {
        "component": name,
        "command": record.get("command") or name,
        "args": ["--version"],
        "expected": record.get("expected") or ">=0",
        "fix": record.get("fix") or "",
        "required": bool(record.get("required", False)),
    }


def sync(json_out: bool = False) -> int:
    """Compare installed state with the record. 0 match, 1 drift, 2 no record."""
    path = record_path()
    if not os.path.isfile(path):
        print("No baseline record at %s -- nothing to sync against." % path)
        print("Write one with the installer's baseline step, then re-run `adk baseline --sync`.")
        return 2
    try:
        with open(path, encoding="utf-8") as handle:
            data = json.load(handle)
    except (OSError, ValueError) as exc:
        print("Cannot read the baseline record at %s: %s" % (path, exc))
        return 2

    recorded = data.get("components") if isinstance(data, dict) else None
    if not isinstance(recorded, list) or not recorded:
        print("The baseline record at %s has no components -- treating as no record." % path)
        return 2

    drift: list[dict] = []
    checked: list[dict] = []
    for item in recorded:
        if not isinstance(item, dict):
            continue
        name = item.get("id") or item.get("component")
        if not name:
            continue
        row = collect(_entry_for(str(name), item))
        checked.append(row)
        expected_state = item.get("state")
        expected_version = item.get("version")
        if row["state"] != "present":
            drift.append(row)
        elif expected_state and row["state"] != expected_state:
            drift.append(row)
        elif expected_version and row["version"] != expected_version:
            drift.append(row)

    if not checked:
        # A non-empty list where nothing is usable is NO record, not a match:
        # a malformed or foreign-format file (``name`` instead of ``id``) must
        # be could-not-judge (2), never "0 on silence" (exit-code doctrine).
        print("The baseline record at %s has components, but none usable "
              "(each needs an `id` or `component`)." % path)
        return 2

    if json_out:
        print(json.dumps(checked, indent=2))
    else:
        for line in format_rows(checked):
            print(line)
        print("")
        if drift:
            print("Drift: %d of %d component(s) no longer match the record."
                  % (len(drift), len(checked)))
        else:
            print("Match: the box is the configuration recorded at %s." % path)
    return 1 if drift else 0


def main(args) -> int:
    if getattr(args, "sync", False):
        return sync(json_out=bool(getattr(args, "json", False)))

    items = rows()
    if getattr(args, "json", False):
        print(json.dumps(items, indent=2))
    else:
        for line in format_rows(items):
            print(line)

    by_name = {entry["component"]: entry for entry in BASELINE}
    broken = [
        row for row in items
        if row["state"] != "present" and by_name[row["component"]]["required"]
    ]
    if broken and not getattr(args, "json", False):
        print("")
        print("Baseline incomplete: %d required component(s) need attention."
              % len(broken))
    return 1 if broken else 0


if __name__ == "__main__":  # pragma: no cover - `python -m adk baseline` uses cli
    sys.exit(main(type("Args", (), {"json": False, "sync": False})()))
