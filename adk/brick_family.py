"""The aw* family as the registry describes it, read from the vendored family.json.

``adk/data/family.json`` is GENERATED by ``gen_ecosystem.py --emit`` from the Aither
World registry (ecosystem.yaml) and shipped inside the wheel, byte-identical to the
monorepo copy; the registry gate EC018 fails when any copy differs from a fresh emit.
It replaced three hand-kept lists in this package (``bricks.FAMILY``, the doctor's
``FAMILY`` and ``integrations._FAMILY``) that each drifted from the registry on their
own schedule.

A missing or unreadable file RAISES :class:`FamilyDataMissingError`. An empty family is
indistinguishable from "no bricks installed", which is the one wrong answer every
caller here would print with confidence.

Stdlib only: ``adk doctor`` and ``adk bricks`` must still run when the thing being
diagnosed is a broken dependency.
"""
from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path
from typing import Any, Dict, List, Optional

DATA_PATH = Path(__file__).resolve().parent / "data" / "family.json"
SCHEMA = "aither-family/1"


class FamilyDataMissingError(RuntimeError):
    """family.json is absent or unreadable -- this install cannot know its family."""


@lru_cache(maxsize=None)
def _load(path: str) -> Dict[str, Any]:
    p = Path(path)
    try:
        doc = json.loads(p.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise FamilyDataMissingError(
            f"cannot read the aw* family index {p} ({type(exc).__name__}: {exc}). It "
            f"ships inside the awdk wheel; reinstall awdk, or in the monorepo run "
            f"`gen_ecosystem.py --emit`.") from exc
    bricks = doc.get("bricks") if isinstance(doc, dict) else None
    if not isinstance(bricks, list) or not bricks or doc.get("schema") != SCHEMA:
        schema = doc.get("schema") if isinstance(doc, dict) else None
        raise FamilyDataMissingError(
            f"{p} is not a {SCHEMA} index with bricks (schema={schema!r}); "
            f"regenerate it with gen_ecosystem.py --emit.")
    return doc


def load(path: Optional[Path] = None) -> Dict[str, Any]:
    """The whole index. Raises FamilyDataMissingError, never returns an empty family."""
    return _load(str(path or DATA_PATH))


def bricks(path: Optional[Path] = None) -> List[Dict[str, Any]]:
    """Every brick record, in registry order."""
    return list(load(path)["bricks"])


def by_id(path: Optional[Path] = None) -> Dict[str, Dict[str, Any]]:
    return {b["id"]: b for b in bricks(path)}
